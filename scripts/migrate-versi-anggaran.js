const { Client } = require('pg');
const fs = require('fs');
const dotenv = require('dotenv');

const env = dotenv.parse(fs.readFileSync('.env'));
const databaseUrl = env.DATABASE_URL.trim().replace(/^["']|["']$/g, '');

async function runMigration() {
  const client = new Client({
    connectionString: databaseUrl,
    ssl: { rejectUnauthorized: false }
  });

  try {
    console.log('Connecting to PostgreSQL via DATABASE_URL...');
    await client.connect();
    console.log('Connected successfully!');

    // 1. Add versi_anggaran to rkat_pengeluaran
    console.log('Migrating rkat_pengeluaran...');
    await client.query(`
      ALTER TABLE public.rkat_pengeluaran 
      ADD COLUMN IF NOT EXISTS versi_anggaran TEXT DEFAULT 'v1';
    `);

    await client.query(`
      UPDATE public.rkat_pengeluaran 
      SET versi_anggaran = 'v1' 
      WHERE versi_anggaran IS NULL;
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_rkat_pengeluaran_versi 
      ON public.rkat_pengeluaran(versi_anggaran, tahun_anggaran);
    `);
    console.log('rkat_pengeluaran migration complete!');

    // 2. Add versi_anggaran to rkat_penerimaan
    console.log('Migrating rkat_penerimaan...');
    await client.query(`
      ALTER TABLE public.rkat_penerimaan 
      ADD COLUMN IF NOT EXISTS versi_anggaran TEXT DEFAULT 'v1';
    `);

    await client.query(`
      UPDATE public.rkat_penerimaan 
      SET versi_anggaran = 'v1' 
      WHERE versi_anggaran IS NULL;
    `);

    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_rkat_penerimaan_versi 
      ON public.rkat_penerimaan(versi_anggaran, tahun);
    `);
    console.log('rkat_penerimaan migration complete!');

    // 3. Create master table for versions: rka_versi_anggaran
    console.log('Creating rka_versi_anggaran table...');
    await client.query(`
      CREATE TABLE IF NOT EXISTS public.rka_versi_anggaran (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        kode_versi TEXT NOT NULL,
        nama_versi TEXT NOT NULL,
        tahun_anggaran INT NOT NULL,
        modul TEXT DEFAULT 'all',
        status TEXT DEFAULT 'aktif',
        keterangan TEXT,
        is_default BOOLEAN DEFAULT false,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
        CONSTRAINT uq_rka_versi UNIQUE(kode_versi, tahun_anggaran, modul)
      );
    `);

    await client.query(`
      ALTER TABLE public.rka_versi_anggaran ENABLE ROW LEVEL SECURITY;
      DROP POLICY IF EXISTS "Allow all access to rka_versi_anggaran" ON public.rka_versi_anggaran;
      CREATE POLICY "Allow all access to rka_versi_anggaran" ON public.rka_versi_anggaran FOR ALL USING (true) WITH CHECK (true);
    `);

    // Insert default versions
    const years = [2024, 2025, 2026, 2027];
    for (const yr of years) {
      await client.query(`
        INSERT INTO public.rka_versi_anggaran 
          (kode_versi, nama_versi, tahun_anggaran, modul, status, is_default, keterangan)
        VALUES 
          ('v1', 'v1 - Murni (Penetapan Awal)', $1, 'all', 'aktif', true, 'Basis data penetapan awal / usulan kementerian')
        ON CONFLICT (kode_versi, tahun_anggaran, modul) DO NOTHING;
      `, [yr]);
    }
    console.log('Default rka_versi_anggaran records created!');

    // Reload PostgREST schema cache
    await client.query("NOTIFY pgrst, 'reload schema';");
    console.log("Notified PostgREST to reload schema!");

    // Verification queries
    const resPeng = await client.query("SELECT COUNT(*) FROM public.rkat_pengeluaran WHERE versi_anggaran = 'v1'");
    const resPen = await client.query("SELECT COUNT(*) FROM public.rkat_penerimaan WHERE versi_anggaran = 'v1'");
    const resVersi = await client.query("SELECT * FROM public.rka_versi_anggaran ORDER BY id ASC");

    console.log('Verification:');
    console.log('- rkat_pengeluaran v1 rows:', resPeng.rows[0].count);
    console.log('- rkat_penerimaan v1 rows:', resPen.rows[0].count);
    console.log('- rka_versi_anggaran count:', resVersi.rows.length);

  } catch (err) {
    console.error('Migration error:', err);
  } finally {
    await client.end();
  }
}

runMigration();
