const { Client } = require('pg');
const fs = require('fs');
const dotenv = require('dotenv');

const env = dotenv.parse(fs.readFileSync('.env'));
const databaseUrl = env.DATABASE_URL.trim().replace(/^["']|["']$/g, '');

async function run() {
  const client = new Client({
    connectionString: databaseUrl,
    ssl: { rejectUnauthorized: false }
  });

  try {
    console.log('Connecting to PostgreSQL...');
    await client.connect();
    console.log('Connected successfully!');

    // 1. Create table rkat_realisasi_tahunan
    console.log('Creating table public.rkat_realisasi_tahunan...');
    await client.query(`
      CREATE TABLE IF NOT EXISTS public.rkat_realisasi_tahunan (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tahun INT NOT NULL,
        jenis VARCHAR(50) NOT NULL,
        kategori VARCHAR(50) NOT NULL,
        sheet_no VARCHAR(20),
        kode_pos VARCHAR(100) NOT NULL,
        nama_pos VARCHAR(255) NOT NULL,
        sub_pos VARCHAR(255) DEFAULT '',
        nilai NUMERIC(20, 2) DEFAULT 0,
        satuan VARCHAR(50) DEFAULT 'Rupiah',
        keterangan TEXT,
        created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
        updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
        CONSTRAINT uq_rkat_realisasi_tahunan UNIQUE (tahun, jenis, kode_pos, sub_pos)
      );
    `);

    // Enable RLS and create open policy
    await client.query(`
      ALTER TABLE public.rkat_realisasi_tahunan ENABLE ROW LEVEL SECURITY;
      DROP POLICY IF EXISTS "Allow all access to rkat_realisasi_tahunan" ON public.rkat_realisasi_tahunan;
      CREATE POLICY "Allow all access to rkat_realisasi_tahunan" ON public.rkat_realisasi_tahunan FOR ALL USING (true) WITH CHECK (true);
    `);

    // Create Indexes for fast querying
    await client.query(`
      CREATE INDEX IF NOT EXISTS idx_rkat_realisasi_tahun_jenis 
      ON public.rkat_realisasi_tahunan(tahun, jenis);

      CREATE INDEX IF NOT EXISTS idx_rkat_realisasi_kategori_sheet 
      ON public.rkat_realisasi_tahunan(kategori, sheet_no);
    `);

    console.log('Table public.rkat_realisasi_tahunan created successfully with RLS and indexes!');

    // Check table info
    const cols = await client.query(`
      SELECT column_name, data_type, is_nullable 
      FROM information_schema.columns 
      WHERE table_name = 'rkat_realisasi_tahunan'
      ORDER BY ordinal_position;
    `);
    console.log('Table columns:');
    console.table(cols.rows);

    // PostgREST reload schema
    await client.query("NOTIFY pgrst, 'reload schema';");
    console.log("PostgREST schema cache reloaded!");

  } catch (err) {
    console.error('Error creating table:', err);
  } finally {
    await client.end();
  }
}

run();
